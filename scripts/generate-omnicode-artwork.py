"""Promote the approved SVG masters to shared application artwork. No dependencies."""
import json
import re
import copy
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / 'design/omnicode-brand-v10'
DEST = ROOT / 'src/shared/ui/branding'
DEST.mkdir(parents=True, exist_ok=True)
ET.register_namespace('', 'http://www.w3.org/2000/svg')
artwork, drawings, styles = {}, {}, []

def tag(node):
    return node.tag.rsplit('}', 1)[-1]

def canvas_parts(node, x=0, y=0, opacity=1):
    transform = node.get('transform', '')
    translate = re.fullmatch(r'translate\(([-\d.]+)[ ,]+([-\d.]+)\)', transform)
    if translate:
        x += float(translate[1])
        y += float(translate[2])
    elif transform:
        raise ValueError(f'Unsupported canvas transform: {transform}')
    opacity *= float(node.get('opacity', 1))
    if tag(node) in ('path', 'circle'):
        if tag(node) == 'circle':
            cx, cy, r = (float(node.get(a)) for a in ('cx', 'cy', 'r'))
            d = f'M {cx-r} {cy} a {r} {r} 0 1 0 {r*2} 0 a {r} {r} 0 1 0 {-r*2} 0'
        else:
            d = node.get('d')
        return [{'d': d, 'x': x, 'y': y, 'opacity': opacity,
                 'strokeWidth': float(node.get('stroke-width', 0)) if node.get('fill') == 'none' else 0}]
    return [part for child in node for part in canvas_parts(child, x, y, opacity)]

for folder, names in [('animated', ['ready', 'thinking', 'running', 'done', 'approval', 'connecting']),
                      ('expressions-8', ['curious', 'inspired', 'focused', 'surprised', 'sleepy', 'joyful', 'encouraging', 'error'])]:
    for name in names:
        svg = ET.parse(DESIGN / folder / f'omi-{name}-current.svg').getroot()
        style, body = list(svg)
        assert tag(style) == 'style' and tag(body) == 'g'
        assert all(tag(node) in ('g', 'path', 'circle') for node in body.iter())
        assert all(not key.startswith('on') for node in body.iter() for key in node.attrib)
        compact = copy.deepcopy(body)
        for extra in list(compact)[1:]:
            compact.remove(extra)
        serialize = lambda node: ET.tostring(node, encoding='unicode').replace(' xmlns="http://www.w3.org/2000/svg"', '').strip()
        face = next(node for node in body.iter() if set(node.get('class', '').split()) & {'omi-face', 'omx-face'})
        artwork[name] = {'className': svg.get('class'), 'markup': serialize(body), 'compactMarkup': serialize(compact), 'faceMarkup': serialize(face)}
        drawings[name] = canvas_parts(list(body)[0])
        styles.append(style.text)

banner = '// Generated by scripts/generate-omnicode-artwork.py from the approved SVG masters.\n'
shapes = json.loads((DESIGN / 'bot-avatars/shapes.json').read_text(encoding='utf-8'))
shapes[0]['outline'] = drawings['ready'][0]['d']
shape_map = {shape['id']: {'outline': shape['outline'], 'faceTransform': shape['faceTransform']} for shape in shapes}
(DEST / 'omiArtwork.ts').write_text(banner + 'export const OMI_ARTWORK = ' + json.dumps(artwork, ensure_ascii=False, indent=2) + ' as const;\n\nexport type OmiExpression = keyof typeof OMI_ARTWORK;\n\nexport const OMI_SHAPES = ' + json.dumps(shape_map, indent=2) + ' as const;\n\nexport type OmiShape = keyof typeof OMI_SHAPES;\n', encoding='utf-8')
(DEST / 'omiCanvas.ts').write_text(banner + 'import type { OmiExpression } from "./omiArtwork";\n\nexport type OmiCanvasPart = { d: string; x: number; y: number; opacity: number; strokeWidth: number };\nexport const OMI_CANVAS: Record<OmiExpression, readonly OmiCanvasPart[]> = ' + json.dumps(drawings, indent=2) + ';\n', encoding='utf-8')
(DEST / 'omi.css').write_text('/* Generated from the approved SVG animation masters. */\n' + '\n'.join(styles) + '''
[data-ui="omi"] { display: block; flex-shrink: 0; overflow: hidden; }
[data-ui="omi"]:not([data-animated]) * { animation: none !important; }
[data-ui="omi"][data-animation-paused] * { animation-play-state: paused !important; }
@media (prefers-reduced-motion: reduce) {
  [data-ui="omi"] * { animation: none !important; }
}
''', encoding='utf-8')

public = ROOT / 'public'
mark = (DESIGN / 'svg/omnicode-mark-current.svg').read_text(encoding='utf-8')
mark = mark.replace('role="img"', 'style="color:#151515" role="img"').replace('<g fill=', '<style>@media(prefers-color-scheme:dark){svg{color:#fff!important}}</style>\n<g fill=', 1)
(public / 'omnicode.svg').write_text(mark, encoding='utf-8')
print('Generated shared Omi artwork, CSS, canvas geometry and favicon')
